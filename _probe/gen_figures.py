def js(x):
    return x.replace("\\", "\\\\").replace("'", "\\'")

# --- EXTRA_FIGURES ---
start = s.index('const EXTRA_FIGURES = [')
end = s.index('\n    ];', start)
figs = []
for (n, r, arc, dyn, y, life, src, d) in F:
    figs.append(
        "      { n: '%s', r: '%s', arc: '%s', dyn: '%s', y: %d, life: '%s', s: '%s', d: '%s' },"
        % (js(n), js(r), arc, js(dyn), y, js(life), js(src), js(d))
    )
s = s[:end] + '\n' + '\n'.join(figs) + s[end:]

# --- FIGURE_LIFE ---
start = s.index('const FIGURE_LIFE = {')
end = s.index('\n    };', start)
